# 5. Prompt Transport Budget handles Tester and downstream Reviewer
# ==============================================================================

def test_prompt_budgeting_truncates_executor_report_for_tester():
    """Verify PromptCompiler.apply_transport_budget truncates executor_report when compiling Tester."""
    role = Role.load("tester")
    large_exec = "# Executor Claims\n" + ("Built feature endpoint.\n" * 1000)
    instruction = Instruction(
        role_name="tester",
        task="Test feature",
        executor_report=large_exec,
    )

    # Budget down to a small size
    budgeted = PromptCompiler.apply_transport_budget(
        instruction=instruction,
        role_template=role.template_content,
        max_prompt_bytes=5000,
    )
    assert budgeted.executor_report is not None
    assert "[... Executor report truncated" in budgeted.executor_report or "[... Executor report omitted" in budgeted.executor_report


def test_prompt_budgeting_truncates_tester_reports_for_reviewer():
    """Verify PromptCompiler.apply_transport_budget truncates tester reports when compiling Reviewer."""
    role = Role.load("reviewer")
