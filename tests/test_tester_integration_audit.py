# ==============================================================================
# 1. Config.default() contains Tester
# ==============================================================================

def test_config_default_contains_tester():
    """Verify Config.default() registers Tester as a first-class default stage."""
    cfg = Config.default()
    assert "tester" in cfg.stages, "Tester must be present in Config.default().stages"
    tester_cfg = cfg.stages["tester"]
    assert tester_cfg.adapter == "opencode"
    assert tester_cfg.effort == "high"

    # Serialized dict must include tester
    cfg_dict = cfg.to_dict()
    assert "tester" in cfg_dict["stages"]
    assert cfg_dict["stages"]["tester"]["adapter"] == "opencode"


# ==============================================================================
# 2. DEFAULT_FORGE_YAML generated by forge init includes Tester
# ==============================================================================

def test_forge_init_generates_tester_in_forge_yaml(tmp_path):
    """Verify forge init generates a forge.yaml containing the tester stage."""
    runner = CliRunner()
    with runner.isolated_filesystem(temp_dir=tmp_path):
        res = runner.invoke(main, ["init"])
        assert res.exit_code == 0
        cfg_file = Path("forge.yaml")
        assert cfg_file.exists()

        content = cfg_file.read_text(encoding="utf-8")
        parsed = yaml.safe_load(content)
        assert "stages" in parsed
        assert "tester" in parsed["stages"], "forge.yaml must include tester stage by default"
        assert parsed["stages"]["tester"].get("effort") == "high"


