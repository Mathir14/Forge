# 6. MachineReportValidator rejects TESTER reports containing SCORES
# ==============================================================================

def test_validator_rejects_tester_scores():
    """Verify MachineReportValidator rejects TESTER reports containing SCORES or SCORE."""
    data = {
        "ROLE": "TESTER",
        "STATUS": "PASS",
        "HANDOFF": "REVIEWER",
        "SCORES": {
            "FUNCTIONALITY": 9,
            "USABILITY": 8,
        },
    }
    report = MachineReportValidator.validate(data, expected_role="TESTER")
    assert report.is_valid is False
    assert any("strictly disallows 'SCORES'" in err for err in report.validation_errors)

    # Also test singular SCORE
    data_singular = {
        "ROLE": "TESTER",
        "STATUS": "PASS",
        "HANDOFF": "REVIEWER",
        "SCORE": 8.5,
    }
    report_singular = MachineReportValidator.validate(data_singular, expected_role="TESTER")
    assert report_singular.is_valid is False
    assert any("strictly disallows 'SCORES'" in err for err in report_singular.validation_errors)


def test_validator_accepts_clean_tester_report():
    """Verify MachineReportValidator accepts clean TESTER report without scores."""
    data = {
        "ROLE": "TESTER",
        "STATUS": "PASS",
        "HANDOFF": "REVIEWER",
        "ISSUES": {
            "CRITICAL": [],
            "MAJOR": [],
        },
    }
    report = MachineReportValidator.validate(data, expected_role="TESTER")
    assert report.is_valid is True
    assert report.status == "PASS"
    assert report.handoff == "REVIEWER"
